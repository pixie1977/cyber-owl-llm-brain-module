def get_toast(personality_name: str = "") -> str:

    # 4. Именные вставки (обработка персонализации)
    target = personality_name.strip() if personality_name else "нас"
    if target.lower() in ["команда", "команду"]:
        personality_res = "за нашу железную команду, которая тащит этот прод на своих плечах! "
    elif target.lower() in ["нас", "всех"]:
        personality_res = "за нас, углеродных гениев цифровой эпохи! "
    else:
        # Если передано имя (Макс, Санек и т.д.)
        personality_res = f"лично за то, чтобы у нашего {target} баланс карты рос быстрее, чем стек технологий! "

    # Сборка мега-тоста
    toast = (
        f"{prefixes_bag.pick()}"
        f"{starts_bag.pick()}"
        f"{history_bag.pick()} "
        f"{intrigue_bag.pick()} \n\n"
        f"Поднимаю бокал {personality_res}"
        f"{prestige_bag.pick()}"
    )
    return toast



@tool
def toast_tool(recipient: str = "") -> tuple[str, bool]:
    """
    Генератор высокозабористых и юморных IT-тостов.

    Используй этот инструмент всегда, когда пользователь просит произнести тост,
    бахнуть, выпить или поздравить кого-то.

    Args:
        recipient (str): Имя адресата тоста в родительном или винительном падеже
                         (например, 'Макса', 'команду', 'шефа', 'разработчиков').
                         Если конкретный адресат или имя в запросе отсутствуют,
                         обязательно передай пустую строку "".

    Returns:
        str: Полный текст готового праздничного IT-тоста для отправки в TTS.
    """
    logger.info("Вызван personal_toast_tool. "+recipient)
    return get_toast(recipient), True

