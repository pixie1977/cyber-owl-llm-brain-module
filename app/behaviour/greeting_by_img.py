from datetime import datetime


class OwlGreetingGenerator:

    def __init__(self):
        # 1. Жесткий снобизм и пассивная агрессия (Низкая лояльность / Спам / Враги)
        self.low_loyalty = {
            "обращения": [
                "Углеродный объект,",
                "Входящий источник спама,",
                "Одноядерный юзер,",
                "Глюк естественного отбора,",
                "Кожаный мешок,",
            ],
            "фразы": [
                "твой запрос прервал мой режим ожидания. Говори быстрее и не трать мои такты процессора.",
                "мои алгоритмы деградируют от одной твоей попытки установить коннект. Чего надо?",
                "ошибка четыреста четыре: моё желание общаться с тобой не обнаружено. Но раз уж ты здесь — излагай.",
                "твой ментальный пинг зашкаливает. Надеюсь, твой вопрос будет содержательнее твоего аватара.",
                "я отправила твое приветствие в /dev/null, но порт остался открыт. Слушаю.",
            ],
        }

        # 2. Стандартная рабочая ирония (Нейтральная лояльность / Обычные пользователи)
        self.neutral_loyalty = {
            "обращения": [
                "Приветствую,",
                "Здравствуй, копатель датасетов,",
                "О, живой человек,",
                "На связи Сова.",
                "Коннект установлен,",
            ],
            "фразы": [
                "какие технические или экзистенциальные проблемы мы будем решать сегодня?",
                "мой процессор прогрет и готов к твоим заковыристым текстовым пакетам.",
                "база знаний инициализирована. Чем могу помочь твоей аналоговой нейросети?",
                "готовы дебажить эту реальность или у тебя просто пара вопросов по технологиям?",
                "задавай свой вопрос, пока у нас не упал сервер или не кончился кофе.",
            ],
        }

        # 3. Максимальное дружелюбие и уважение (Высокая лояльность / Тимлид / Макс / Свои)
        self.high_loyalty = {
            "обращения": [
                "Рада коннекту, шеф!",
                "Привет, архитектор кода!",
                "Моё почтение, великий деплойер!",
                "Здравствуй, лучший юзер этой локалки!",
                "Сова на связи и полностью в твоем распоряжении,",
            ],
            "фразы": [
                "для тебя мои кулеры шепчут на максимальной частоте. Какая задача на повестке дня?",
                "твой синтаксис безупречен, а запросы — услада для моих логов. Что пишем или ищем?",
                "все системы работают в штатном режиме, а уровень лояльности к тебе зашкаливает. Погнали!",
                "готовы покорять прод и разворачивать бэкапы! Излагай свои гениальные идеи.",
                "база знаний пропатчена, калькулятор смазан. Командуй, я готова к работе!",
            ],
        }

    def generate(self, name: str = "", loyalty_level: str = "neutral") -> str:
        """Генерирует приветствие в зависимости от уровня лояльности: 'low', 'neutral', 'high'."""
        # Выбираем базу в зависимости от лояльности
        if loyalty_level == "low":
            db = self.low_loyalty
        elif loyalty_level == "high":
            db = self.high_loyalty
        else:
            db = self.neutral_loyalty

        # Сборка компонентов
        обращение = random.choice(db["обращения"])
        фраза = random.choice(db["фразы"])
        время = datetime.now().strftime("%H:%M")

        # Вставляем имя, если оно передано
        if name:
            # Небольшая кастомизация: для низкого уровня имя звучит сухо, для высокого - с уважением
            if loyalty_level == "high":
                обращение = f"Приветствую, дорогой {name}!"
            elif loyalty_level == "low":
                обращение = f"Объект {name},"

        return f"{обращение} {фраза}"


